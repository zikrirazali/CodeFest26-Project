function t(key, vars = {}) {
  const s = STRINGS[I18n.lang][key] ?? STRINGS.en[key] ?? key;
  return s.replace(/\{(\w+)\}/g, (_, k) => vars[k] ?? "");
}

// Pick the current-language variant of an API field: L(obj, "title") -> obj.title_ms / obj.title_en
function L(obj, field) {
  return obj[`${field}_${I18n.lang}`] || obj[`${field}_en`] || "";
}
